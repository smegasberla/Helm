#!/usr/bin/env bash
#
# Add a second boot entry that reserves the dedicated card for vfio-pci.
#
# The guest profile hands the card over by unbinding it from the host driver at
# launch time. Doing that from a live graphical session is what wedges the driver
# core: the NVIDIA module tears down a device that userspace still holds through
# /dev/nvidiactl, the kernel oopses, and the card stays driverless until the next
# reboot. Reserving the card at boot removes the unbind entirely - it never
# belongs to the host driver in that boot, so there is nothing to take away.
#
# Nothing here touches the running system's configuration for the current boot
# entry: the default cmdline, its preset and its UKI are read, recorded and left
# byte-identical. Only new files are added.
#
# usage: sudo packaging/linux/vfio-boot-entry.sh [vendor:device]
#
set -euo pipefail

# The RTX 3060 of this machine; the guest profile's GPU address is 0000:01:00.0.
GPU_ID="${1:-10de:2520}"

ENTRY="arch-linux-helm"
CONFIG="/etc/mkinitcpio.conf-helm"
CMDLINE="/etc/kernel/cmdline-helm"
PRESET="/etc/mkinitcpio.d/linux-helm.preset"
LOADER_ENTRY="/boot/loader/entries/${ENTRY}.conf"
DEFAULT_UKI="/boot/EFI/Linux/arch-linux.efi"
HELM_UKI="/boot/EFI/Linux/${ENTRY}.efi"
SPLASH="/usr/share/systemd/bootctl/splash-arch.bmp"
STAMP="$(date +%Y%m%d-%H%M%S)"

say() { printf '%s\n' "$*"; }
die() { printf 'error: %s\n' "$*" >&2; exit 1; }

[[ ${EUID} -eq 0 ]] || die "this has to run as root: sudo $0 $GPU_ID"
[[ -d /etc/mkinitcpio.d ]] || die "mkinitcpio presets are not where this script expects them"
[[ -f ${DEFAULT_UKI} ]] || die "the default UKI ${DEFAULT_UKI} is missing; run mkinitcpio -P first"
command -v objcopy >/dev/null || die "objcopy is missing: install binutils"

say "== free space on the ESP =="
AVAIL_MIB="$(df -Pm /boot | awk 'NR == 2 { print $4 }')"
say "available: ${AVAIL_MIB} MiB"
[[ ${AVAIL_MIB} -ge 200 ]] || die "the ESP needs at least 200 MiB for a second UKI"

say
say "== the default entry, before anything is written =="
DEFAULT_CMDLINE="$(cat /etc/kernel/cmdline)"
DEFAULT_UKI_HASH="$(sha256sum "${DEFAULT_UKI}" | awk '{ print $1 }')"
say "cmdline: ${DEFAULT_CMDLINE}"
say "uki:     ${DEFAULT_UKI_HASH}"

say
say "== backups =="
mkdir -p "/var/backups/helm-${STAMP}"
cp -a /etc/kernel/cmdline "/var/backups/helm-${STAMP}/cmdline"
cp -a /etc/mkinitcpio.conf "/var/backups/helm-${STAMP}/mkinitcpio.conf"
cp -a /etc/mkinitcpio.d/linux.preset "/var/backups/helm-${STAMP}/linux.preset"
say "copied to /var/backups/helm-${STAMP}"

# The vfio boot needs a modules list of its own. Keeping it in a separate config
# leaves the default UKI's module set - and therefore its bytes - untouched.
say
say "== ${CONFIG} =="
sed -e "s|^MODULES=.*|MODULES=(vfio_pci vfio_pci_core vfio_iommu_type1 kvmfr)|" \
    /etc/mkinitcpio.conf > "${CONFIG}"
grep -nE '^MODULES=' "${CONFIG}"

# The card id is passed on the kernel command line rather than in modprobe.d:
# a modprobe option would apply to every boot, including the one that is supposed
# to keep the card on the NVIDIA driver.
say
say "== ${CMDLINE} =="
printf '%s vfio-pci.ids=%s\n' "${DEFAULT_CMDLINE}" "${GPU_ID}" > "${CMDLINE}"
cat "${CMDLINE}"

say
say "== ${PRESET} =="
cat > "${PRESET}" <<EOF
# Second boot entry: the dedicated card belongs to vfio-pci for the whole boot.
# Generated by packaging/linux/vfio-boot-entry.sh; the default preset is untouched.

ALL_config="${CONFIG}"
ALL_kver="/boot/vmlinuz-linux"

PRESETS=('default')

default_uki="${HELM_UKI}"
default_options="--splash ${SPLASH} --cmdline ${CMDLINE}"
EOF
grep -vE '^$|^#' "${PRESET}"

# systemd-boot names a UKI after its path, which would read as "arch-linux-helm"
# in the menu; an entry file of the same name replaces that title.
say
say "== ${LOADER_ENTRY} =="
cat > "${LOADER_ENTRY}" <<EOF
title   Helm (Windows VM, vfio-pci)
linux   /EFI/Linux/${ENTRY}.efi
EOF
cat "${LOADER_ENTRY}"

say
say "== building only the new entry =="
mkinitcpio -p "${PRESET}"

say
say "== the cmdline actually embedded in the new UKI =="
EMBEDDED="$(objcopy -O binary --only-section=.cmdline "${HELM_UKI}" /dev/stdout 2>/dev/null | tr -d '\0')"
say "${EMBEDDED}"
case "${EMBEDDED}" in
    *"vfio-pci.ids=${GPU_ID}"*) say "vfio-pci.ids is embedded" ;;
    *) die "the new UKI does not carry vfio-pci.ids=${GPU_ID}" ;;
esac
lsinitcpio "${HELM_UKI}" | grep -qi vfio || die "vfio modules are missing from the new initramfs"
say "vfio modules are in the new initramfs"

say
say "== the default entry, after =="
AFTER_HASH="$(sha256sum "${DEFAULT_UKI}" | awk '{ print $1 }')"
say "uki:     ${AFTER_HASH}"
[[ "${AFTER_HASH}" == "${DEFAULT_UKI_HASH}" ]] && say "unchanged" || die "the default UKI changed"
[[ "$(cat /etc/kernel/cmdline)" == "${DEFAULT_CMDLINE}" ]] && say "default cmdline unchanged"

say
say "== boot entries =="
bootctl list 2>/dev/null | grep -E 'title:|id:' || bootctl list

say
say "Done. The default entry still boots exactly as before."
say "Pick 'Helm (Windows VM, vfio-pci)' at boot to run the guest profile."
say "In that boot nvidia-smi must fail: readlink /sys/bus/pci/devices/0000:01:00.0/driver"
say "has to print .../drivers/vfio-pci instead."
